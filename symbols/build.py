def read_grid(src):
    """Parse a grid and crop it to its ink, so every symbol centres the same."""
    rows = src.strip("\n").split("\n")
    width = max(len(r) for r in rows)
    bits = [[c == "#" for c in r.ljust(width, ".")] for r in rows]
    while not any(bits[0]):
        bits.pop(0)
    while not any(bits[-1]):
        bits.pop()
    cols = [x for x in range(width) if any(r[x] for r in bits)]
    return [r[cols[0]:cols[-1] + 1] for r in bits]


def runs(row):
    x = 0
    while x < len(row):
        if row[x]:
            start = x
            while x < len(row) and row[x]:
                x += 1
            yield start, x
        else:
            x += 1


def svg(bits, cell_w=PX, cell_h=PX):
    parts = [f"M{a * cell_w:g} {y * cell_h:g}h{(b - a) * cell_w:g}v{cell_h:g}h{-(b - a) * cell_w:g}z"
             for y, row in enumerate(bits) for a, b in runs(row)]
    w, h = len(bits[0]) * cell_w, len(bits) * cell_h
    # A square canvas with the ink centred in the middle ~77%, the proportions
    # the unlock animation lays out its status line around.
    side = round(max(w, h) / INK)
    x0, y0 = (w - side) / 2, (h - side) / 2
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{side:g}" height="{side:g}" '
            f'viewBox="{x0:g} {y0:g} {side:g} {side:g}">'
            f'<path fill="#ffffff" d="{"".join(parts)}"/></svg>\n')


def omarchy_grid(path="/usr/share/omarchy/icon.txt"):
    """Omarchy's icon is drawn in text rows twice as tall as a column; keep
    every other row and treat four columns as one square pixel."""
    rows = [r.rstrip("\n") for r in open(path, encoding="utf-8")]
    rows = [r for r in rows if r.strip()][::2]
    width = max(len(r) for r in rows)
    return [[c == "█" for c in r.ljust(width)] for r in rows]


def main():
    out = {}
    for name, src in SYMBOLS.items():
        out[name] = svg(read_grid(src))
    if os.path.exists("/usr/share/omarchy/icon.txt"):
        g = omarchy_grid()
        # 54 columns x 13 rows: one row is about 4.15 columns tall.
        out["omarchy"] = svg(g, cell_w=PX / 4, cell_h=PX * len(g[0]) / 4 / len(g))
    for name, text in out.items():
        with open(os.path.join(HERE, name + ".svg"), "w") as f:
            f.write(text)
    # The same pixels for animations that work per pixel (grids.json): rows of
    # "#"/"." cropped to the ink. In the SVGs the ink is centred in a square and
    # its longer side spans INK of the canvas. cellAspect is a cell's height over
    # its width: 1 for the pixel grids; Omarchy's traced cells are taller.
    grids = {name: {"rows": ["".join("#" if b else "." for b in r) for r in read_grid(src)], "cellAspect": 1}
             for name, src in SYMBOLS.items()}
    if os.path.exists("/usr/share/omarchy/icon.txt"):
        g = omarchy_grid()
        grids["omarchy"] = {"rows": ["".join("#" if b else "." for b in r) for r in g],
                            "cellAspect": len(g[0]) / len(g)}
    with open(os.path.join(HERE, "grids.json"), "w") as f:
        json.dump({"ink": INK, "symbols": grids}, f, separators=(",", ":"))
    print("\n".join(sorted(out)))


if __name__ == "__main__":
    sys.exit(main())
