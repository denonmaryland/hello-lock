#!/usr/bin/env python3
"""Precompute waveform peaks for the Settings sound page.

Writes settings/SoundPeaks.js from the bundled WAVs so Settings never decodes
audio at runtime. Each cue gets its duration and a row of peak bars (the
loudest sample in each slice, scaled so the cue's loudest slice is 1); the
unlock cue also gets a finer row for the large waveform. Standard library
only and reproducible. Run after regenerating sounds:
  python3 sounds/peaks.py
  python3 sounds/peaks.py --check   # exit 1 if SoundPeaks.js is stale
"""
import argparse
from array import array
from pathlib import Path
import sys
import wave

SOUNDS = Path(__file__).resolve().parent
OUT = SOUNDS.parent / "settings" / "SoundPeaks.js"
ROW_BARS = 40
HERO_BARS = 175
TYPING = ["pulse", "phase", "flux", "grain", "drift", "circuit"]
CUES = ["lock", "error", "unlock-coin"] + ["type-%s-1" % f for f in TYPING]


def read(path):
    with wave.open(str(path), "rb") as audio:
        if audio.getsampwidth() != 2:
            raise ValueError("%s: expected 16-bit PCM" % path.name)
        channels = audio.getnchannels()
        rate = audio.getframerate()
        frames = audio.getnframes()
        data = array("h")
        data.frombytes(audio.readframes(frames))
    if sys.byteorder == "big":
        data.byteswap()
    # Loudest channel per frame.
    mono = [max(abs(data[i + c]) for c in range(channels)) for i in range(0, len(data), channels)]
    return mono, frames / rate


def bars(samples, count):
    size = len(samples) / count
    peaks = []
    for i in range(count):
        part = samples[int(i * size):max(int(i * size) + 1, int((i + 1) * size))]
        peaks.append(max(part) if part else 0)
    top = max(peaks) or 1
    return [round(p / top, 3) for p in peaks]


def render():
    lines = [
        ".pragma library",
        "",
        "// Generated by sounds/peaks.py from the bundled WAVs. Do not edit; rerun",
        "// the script after changing a sound. duration in seconds; peaks 0..1.",
        "var cues = {",
    ]
    entries = []
    for name in CUES:
        samples, duration = read(SOUNDS / (name + ".wav"))
        entry = '  "%s": { duration: %s, peaks: [%s]' % (
            name, round(duration, 3), ", ".join(str(p) for p in bars(samples, ROW_BARS)))
        if name == "unlock-coin":
            entry += ", hero: [%s]" % ", ".join(str(p) for p in bars(samples, HERO_BARS))
        entries.append(entry + " }")
    lines.append(",\n".join(entries))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if settings/SoundPeaks.js is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("settings/SoundPeaks.js is stale; run python3 sounds/peaks.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote " + str(OUT.relative_to(SOUNDS.parent)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
