HEIGHT = 16
SPACE_WIDTH = 5
LETTER_GAP = 2


def glyph(ch):
    rows = [r for r in GLYPHS[ch].strip("\n").split("\n")]
    width = max(len(r) for r in rows)
    return [r.ljust(width, ".") for r in rows]


def check():
    for ch, src in GLYPHS.items():
        rows = src.strip("\n").split("\n")
        assert len(rows) == HEIGHT, (ch, len(rows))
        assert len({len(r) for r in rows}) == 1, (ch, "ragged rows")
        assert set("".join(rows)) <= {"#", "."}, ch
